CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE members (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(254) NOT NULL,
    nickname varchar(50) NOT NULL,
    profile_image_key varchar(1024),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT uq_members_email UNIQUE (email),
    CONSTRAINT ck_members_email CHECK (btrim(email) <> ''),
    CONSTRAINT ck_members_nickname CHECK (btrim(nickname) <> '')
);

CREATE TABLE member_credentials (
    member_id bigint PRIMARY KEY REFERENCES members (id),
    password_hash varchar(255) NOT NULL,
    password_changed_at timestamptz NOT NULL
);

CREATE TABLE auth_sessions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL REFERENCES members (id),
    refresh_token_hash varchar(128) NOT NULL,
    issued_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz,
    CONSTRAINT uq_auth_sessions_refresh_token_hash UNIQUE (refresh_token_hash),
    CONSTRAINT ck_auth_sessions_expiry CHECK (expires_at > issued_at)
);
CREATE INDEX ix_auth_sessions_member ON auth_sessions (member_id);

CREATE TABLE courses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creator_id bigint NOT NULL REFERENCES members (id),
    title varchar(100) NOT NULL,
    route geometry(LineString,4326) NOT NULL,
    estimated_distance_m double precision NOT NULL,
    is_loop boolean NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    deleted_at timestamptz,
    CONSTRAINT ck_courses_title CHECK (btrim(title) <> ''),
    CONSTRAINT ck_courses_distance CHECK (estimated_distance_m >= 0 AND estimated_distance_m < 'Infinity'::double precision),
    CONSTRAINT ck_courses_route CHECK (
        NOT ST_IsEmpty(route) AND ST_NPoints(route) BETWEEN 2 AND 50
        AND ST_XMin(Box3D(route)) >= -180 AND ST_XMax(Box3D(route)) <= 180
        AND ST_YMin(Box3D(route)) >= -90 AND ST_YMax(Box3D(route)) <= 90
    )
);
CREATE INDEX ix_courses_creator_created ON courses (creator_id, created_at DESC, id DESC) WHERE deleted_at IS NULL;

CREATE TABLE crews (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL,
    owner_member_id bigint NOT NULL REFERENCES members (id),
    invite_code varchar(32) NOT NULL,
    max_members smallint NOT NULL DEFAULT 10,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT uq_crews_invite_code UNIQUE (invite_code),
    CONSTRAINT ck_crews_name CHECK (btrim(name) <> ''),
    CONSTRAINT ck_crews_max_members CHECK (max_members > 0)
);

CREATE TABLE crew_members (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crew_id bigint NOT NULL REFERENCES crews (id),
    member_id bigint NOT NULL REFERENCES members (id),
    joined_at timestamptz NOT NULL,
    left_at timestamptz
);
CREATE UNIQUE INDEX uq_crew_members_active ON crew_members (crew_id, member_id) WHERE left_at IS NULL;
CREATE INDEX ix_crew_members_member_active ON crew_members (member_id, crew_id) WHERE left_at IS NULL;

CREATE TABLE running_sessions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crew_id bigint NOT NULL REFERENCES crews (id),
    created_by bigint NOT NULL REFERENCES members (id),
    course_id bigint NOT NULL REFERENCES courses (id),
    title varchar(100) NOT NULL,
    status varchar(24) NOT NULL,
    planned_course_title varchar(100) NOT NULL,
    planned_route geometry(LineString,4326) NOT NULL,
    planned_distance_m double precision NOT NULL,
    planned_is_loop boolean NOT NULL,
    crew_name_snapshot varchar(100) NOT NULL,
    created_at timestamptz NOT NULL,
    started_at timestamptz,
    completed_at timestamptz,
    CONSTRAINT ck_running_sessions_title CHECK (btrim(title) <> ''),
    CONSTRAINT ck_running_sessions_distance CHECK (planned_distance_m >= 0 AND planned_distance_m < 'Infinity'::double precision),
    CONSTRAINT ck_running_sessions_route CHECK (
        NOT ST_IsEmpty(planned_route) AND ST_NPoints(planned_route) BETWEEN 2 AND 50
        AND ST_XMin(Box3D(planned_route)) >= -180 AND ST_XMax(Box3D(planned_route)) <= 180
        AND ST_YMin(Box3D(planned_route)) >= -90 AND ST_YMax(Box3D(planned_route)) <= 90
    ),
    CONSTRAINT ck_running_sessions_state CHECK (
        (status = 'WAITING' AND started_at IS NULL AND completed_at IS NULL)
        OR (status = 'RUNNING' AND started_at IS NOT NULL AND completed_at IS NULL)
        OR (status = 'COMPLETED' AND started_at IS NOT NULL AND completed_at IS NOT NULL AND completed_at >= started_at)
    )
);
CREATE UNIQUE INDEX uq_running_session_per_crew ON running_sessions (crew_id) WHERE status = 'RUNNING';
CREATE INDEX ix_running_sessions_crew_status_created ON running_sessions (crew_id, status, created_at DESC, id DESC);

CREATE TABLE session_participants (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id bigint NOT NULL REFERENCES running_sessions (id),
    member_id bigint NOT NULL REFERENCES members (id),
    status varchar(24) NOT NULL,
    joined_at timestamptz NOT NULL,
    started_at timestamptz,
    ended_at timestamptz,
    CONSTRAINT uq_session_participants_session_member UNIQUE (session_id, member_id),
    CONSTRAINT ck_session_participants_state CHECK (
        (status IN ('JOINED', 'ABSENT') AND started_at IS NULL AND ended_at IS NULL)
        OR (status = 'RUNNING' AND started_at IS NOT NULL AND ended_at IS NULL)
        OR (status = 'FINISHED' AND started_at IS NOT NULL AND ended_at IS NOT NULL AND ended_at >= started_at)
    )
);
CREATE UNIQUE INDEX uq_running_participant_per_member ON session_participants (member_id) WHERE status = 'RUNNING';
CREATE INDEX ix_session_participants_member_finished ON session_participants (member_id, ended_at DESC, id DESC) WHERE status = 'FINISHED';

CREATE TABLE gps_events (
    event_id uuid PRIMARY KEY,
    participant_id bigint NOT NULL REFERENCES session_participants (id),
    sequence bigint NOT NULL,
    ingest_order bigint NOT NULL,
    location geometry(Point,4326) NOT NULL,
    accuracy_m double precision NOT NULL,
    recorded_at timestamptz NOT NULL,
    received_at timestamptz NOT NULL,
    validation_status varchar(24) NOT NULL,
    rejection_reason varchar(64),
    processed_at timestamptz,
    CONSTRAINT uq_gps_events_participant_sequence UNIQUE (participant_id, sequence),
    CONSTRAINT uq_gps_events_participant_ingest UNIQUE (participant_id, ingest_order),
    CONSTRAINT ck_gps_events_sequence CHECK (sequence >= 0),
    CONSTRAINT ck_gps_events_ingest_order CHECK (ingest_order > 0),
    CONSTRAINT ck_gps_events_accuracy CHECK (accuracy_m >= 0 AND accuracy_m < 'Infinity'::double precision),
    CONSTRAINT ck_gps_events_location CHECK (
        NOT ST_IsEmpty(location)
        AND ST_X(location) BETWEEN -180 AND 180 AND ST_Y(location) BETWEEN -90 AND 90
    ),
    CONSTRAINT ck_gps_events_validation CHECK (
        (validation_status = 'PENDING' AND processed_at IS NULL AND rejection_reason IS NULL)
        OR (validation_status = 'VALID' AND processed_at IS NOT NULL AND rejection_reason IS NULL)
        OR (validation_status = 'REJECTED' AND processed_at IS NOT NULL AND rejection_reason IS NOT NULL)
    )
);
CREATE INDEX ix_gps_events_pending ON gps_events (participant_id, ingest_order) WHERE validation_status = 'PENDING';

CREATE TABLE record_jobs (
    participant_id bigint PRIMARY KEY REFERENCES session_participants (id),
    status varchar(24) NOT NULL,
    cutoff_ingest_order bigint NOT NULL,
    attempt_count integer NOT NULL DEFAULT 0,
    error_code varchar(64),
    requested_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    completed_at timestamptz,
    CONSTRAINT ck_record_jobs_cutoff CHECK (cutoff_ingest_order >= 0),
    CONSTRAINT ck_record_jobs_attempt_count CHECK (attempt_count >= 0),
    CONSTRAINT ck_record_jobs_state CHECK (
        (status IN ('PROCESSING', 'FAILED') AND completed_at IS NULL)
        OR (status = 'COMPLETED' AND completed_at IS NOT NULL)
    )
);
CREATE INDEX ix_record_jobs_status_updated ON record_jobs (status, updated_at);

CREATE TABLE running_records (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_id bigint NOT NULL REFERENCES session_participants (id),
    distance_m double precision NOT NULL,
    duration_seconds bigint NOT NULL,
    calculation_version varchar(32) NOT NULL,
    created_at timestamptz NOT NULL,
    CONSTRAINT uq_running_records_participant UNIQUE (participant_id),
    CONSTRAINT ck_running_records_distance CHECK (distance_m >= 0 AND distance_m < 'Infinity'::double precision),
    CONSTRAINT ck_running_records_duration CHECK (duration_seconds >= 0)
);
